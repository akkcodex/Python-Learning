# =========================
# WHAT IS PYTHON?
# =========================

# Python is a high-level, interpreted, general-purpose programming language.
# It was developed by Guido van Rossum and released in 1991.

# =========================
# TYPES OF PYTHON
# =========================

# 1) Python is a General-Purpose Programming Language.
# 2) Python is a High-Level Programming Language.
# 3) Python is an Interpreted Programming Language.
# 4) Python has English-like and easy-to-read syntax.
# 5) Python is a Dynamically Typed Programming Language.
# 6) Python is a Case-Sensitive Programming Language.
# 7) Python is a Multi-Paradigm Programming Language.
# 8) Python supports Procedural Programming.
# 9) Python supports Object-Oriented Programming (OOP).
# 10) Python supports Functional Programming.
# 11) Python supports Modular Programming.

